def load_lines(rel):
    path = os.path.join(REPO, rel.replace("/", os.sep))
    if not os.path.isfile(path):
        raise SystemExit("源文件不存在：%s" % rel)
    with io.open(path, "r", encoding="utf-8-sig", errors="replace") as f:
        return f.read().split("\n")


def quote(rel, a, b):
    lines = load_lines(rel)
    if not (1 <= a <= b <= len(lines)):
        raise SystemExit("行号越界：%s %d-%d（共 %d 行）" % (rel, a, b, len(lines)))
    block = lines[a - 1:b]
    while block and not block[-1].strip():
        block.pop()
    out = []
    for ln in block:
        out.append(">" if not ln.strip() else "> " + ln)
    return out


def render_page(pg, dep):
    pid, title, field, sources, note = pg
    out = []
    out.append("### %s · %s" % (pid, title))
    out.append("")
    out.append("- **对应模板**：%s" % field)
    loc = "；".join("`%s` 第 %d–%d 行" % (rel, a, b) for rel, a, b in sources)
    out.append("- **出处（包外，见 `14` %s）**：%s" % (dep, loc))
    out.append("- **摘录性质**：逐字原文，未改一字（引用块前缀 `> ` 为排版标记；原书旧译名、旧参数、旧编号一律保留）")
    out.append("")
    for i, (rel, a, b) in enumerate(sources):
        if i:
            out.append("> ")
            out.append("> —— 同页续摘：`%s` 第 %d–%d 行 ——" % (rel, a, b))
            out.append("> ")
        else:
            out.append("> 〔本页原文起：`%s` 第 %d–%d 行〕" % (rel, a, b))
            out.append("> ")
        out.extend(quote(rel, a, b))
        out.append("")
    out.append("- **填法要点（编者按，非原文）**：%s" % note)
    out.append("")
    return out


