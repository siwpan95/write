import io, re, sys

p = '第221章-白塔之战（下）.txt'
s = io.open(p, encoding='utf-8').read()

anchor = '他站在自己菌丝堆上。'
assert anchor in s, 'anchor missing'

add = '''他站在自己菌丝堆上。

他往下看。

他看见那些菌丝在往塔底上爬——不是听他的，是自己爬。

它们认那口井。

——

他忽然停了手。

他把一只手从塔壁上收回来，按在自己胸口。

那只手已经散了大半，按上去没有形状。

他按了两下，摸着了。

胸口里有东西。

不是心。

是一根硬的东西，横在那儿，一端往里，一端往外。

他记得这个东西。

他在这片土上走了三年，走的时候它就在。他被压到只剩一层皮的时候，剩的那层皮里就有这个东西。

他从来没问过它是什么。

今天他问了。

他把它往外抽了一点。

抽出来一截。

那是一层薄的东西，卷着，卷成筒。

他把它捏在手里看了一眼。

灰的。

跟菌丝不一样。

——

王把手又举起来了。

主角在门后头看着。

他看见那只手在往上举，举到一半停住。

停住的原因是王在看自己手里那卷东西。

他说，我忘了这是什么。

主角说，你没忘。

王说，我忘了。

他说，我在这片土上走了三年，见过十几次有人从土底下出来。出来的时候身上都带着这个东西。

他说，我还以为那是他们的骨头。

——

主角说，那不是骨头。

王说，那是什么。

主角说，那是有人替他们收的。

——

王把那卷东西塞回胸口。

塞的时候他手停了一下。

他说，收的。

他说，那收的人呢。

主角说，走了。

王说，都走了。

他说，那这一卷还留着干什么。

——

主角没答。

他感觉到网在抖。

不是有人在抖。

是那四百一十七个人的脚底下，有一小块土在往下陷。

王也抬头了。

他看了很久。

他说，它要扎了。
'''

s = s.replace(anchor, add, 1)
io.open(p, 'w', encoding='utf-8').write(s)

pat = re.compile(r'[\u4e00-\u9fff\u3400-\u4dbf]')
n = 0
for i, line in enumerate(io.open(p, encoding='utf-8')):
    if i == 0:
        continue
    t = line.strip()
    if not t or t.startswith('==='):
        continue
    n += len(pat.findall(line))
print('wc', n)
