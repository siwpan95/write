def read_clean(path, heading):
    """剥离索引卡块（自 '## 本章索引卡' 起至其后第一个 '---'），替换一级标题。"""
    with open(path, encoding='utf-8') as f:
        lines = f.read().split('\n')
    out = []
    skipping = False
    for line in lines:
        if line.startswith('## 本章索引卡'):
            skipping = True
            continue
        if skipping:
            if line.strip() == '---':
                skipping = False
            continue
        if line.startswith('# ') and not out:
            out.append(heading)
            continue
        out.append(line)
    # 合并多余空行，保留原有段落结构
    text = '\n'.join(out)
    while '\n\n\n' in text:
        text = text.replace('\n\n\n', '\n\n')
    return text.strip()


