ok, miss = 0, []
for pre, old, new in R:
    p = find(pre)
    if not p:
        miss.append((pre, '文件缺失', old[:20])); continue
    t = open(p, encoding='utf-8').read()
    c = t.count(old)
    if c == 0:
        miss.append((pre, '未命中', old[:30])); continue
    if APPLY:
        open(p, 'w', encoding='utf-8').write(t.replace(old, new))
    ok += 1
    print('OK', pre, f'x{c}', old[:22], '→', new[:26])

# D11 全局：免予刑事处分 → 免予刑事处罚
