hits, miss = 0, []
for pre, old, new, exp in R:
    p = find(pre)
    if not p:
        miss.append((pre, '文件未找到', old[:20]))
        continue
    t = open(p, encoding='utf-8').read()
    c = t.count(old)
    if c == 0:
        miss.append((pre, '原文未命中', old[:28]))
        continue
    if exp > 0 and c != exp:
        miss.append((pre, f'次数不符({c}!={exp})', old[:28]))
        continue
    if APPLY:
        open(p, 'w', encoding='utf-8').write(t.replace(old, new))
    hits += 1
    print('OK', pre, f'×{c}', old[:24], '→', new[:24])

