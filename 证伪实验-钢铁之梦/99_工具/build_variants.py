    kind="叙述层——不增 e₁，把两处「明确否认」改成「含糊回避」，拆掉叙述的对账功能",
    points="第13、19行（两处 @@N）整行替换；其余 24 行未动；@@N 计数仍为 2",
    lines=v1,
