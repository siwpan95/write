# ---------------- 引号归一 + 写出 ----------------
def norm(s):
    return s.replace("\u201c", '"').replace("\u201d", '"')


report = []
for vid, cfg in VARIANTS.items():
    cfg["lines"] = [norm(x) for x in cfg["lines"]]
    body = "\n".join(cfg["lines"])
    head = HEAD.format(vid=vid, name=cfg["name"], kind=cfg["kind"], points=cfg["points"])
    path = OUT / (vid + "_" + cfg["name"].split("（")[0] + ".md")
    path.write_text(head + "\n```\n" + body + "\n```\n", encoding="utf-8")
    zh = len(re.findall(r"[\u4e00-\u9fff]",
                        "\n".join(re.sub(r"^@@\w+\|?", "", l).replace("|", " ") for l in cfg["lines"])))
    report.append((vid, cfg["name"], len(cfg["lines"]), zh, zh / 1343 * 100 - 100))

print("变体  名称                       行数   汉字   相对基线")
for vid, name, n, zh, pct in report:
    print(f"{vid}   {name:<24} {n:>3}  {zh:>5}   {pct:+.1f}%")
print("基线 V0                         26   1343")
print("篇幅保真区间（±20%）：1074 – 1612")
