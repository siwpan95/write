def load(path: Path):
    raw = path.read_bytes()
    bom = raw.startswith(b"\xef\xbb\xbf")
    body = raw[3:] if bom else raw
    crlf = b"\r\n" in body
    return body.decode("utf-8"), bom, crlf


def save(path: Path, text: str, bom: bool, crlf: bool):
    if crlf:
        text = text.replace("\r\n", "\n").replace("\n", "\r\n")
    data = text.encode("utf-8")
    if bom:
        data = b"\xef\xbb\xbf" + data
    path.write_bytes(data)


def main() -> int:
    # 仓根由脚本位置推导，避免写死本机绝对路径导致跨机失效。
    default_root = Path(__file__).resolve().parent.parent.parent
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=str(default_root), help="仓根目录（默认由脚本位置推导）")
    ap.add_argument("--apply", action="store_true", help="真正写入；默认只预览")
    args = ap.parse_args()
    root = Path(args.root)

    by_file = {}
    for rel, old, new in FIXES:
        if not old or old == new:
            continue
        by_file.setdefault(rel, []).append((old, new))

    total_hit = 0
    for rel, pairs in by_file.items():
        p = root / rel
        if not p.exists():
            print(f"  × 文件不存在  {rel}")
            continue
        text, bom, crlf = load(p)
        for old, new in pairs:
            n = text.count(old)
            if n == 0:
                print(f"  ! 未命中  {rel}  「{old[:30]}」")
                continue
            text = text.replace(old, new)
            total_hit += n
            print(f"  ✓ {rel}  {n} 处")
            print(f"      旧 「{old[:60]}」")
            print(f"      新 「{new[:60]}」")
        if args.apply:
            save(p, text, bom, crlf)

    print(f"\n共替换 {total_hit} 处  {'（已写入）' if args.apply else '（预览，未写入）'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
